/// Generate the JSON Schema bundle used by the desktop SDK runtime validator.
pub fn generate_protocol_schema_json() -> String {
    let bundle = protocol_schema_bundle();
    serde_json::to_string_pretty(&bundle).expect("serialize desktop protocol schema")
}

/// Write generated ACP TypeScript wire types to `output_dir`.
pub fn write_acp_typescript_dir(output_dir: impl AsRef<Path>) -> io::Result<()> {
    let output_dir = output_dir.as_ref();
    if output_dir.exists() {
        fs::remove_dir_all(output_dir)?;
    }
    fs::create_dir_all(output_dir)?;
    fs::write(output_dir.join("acp.ts"), generate_acp_typescript())?;
    fs::write(
        output_dir.join("protocol.ts"),
        generate_protocol_typescript(),
    )?;
    fs::write(
        output_dir.join("schema.json"),
        generate_protocol_schema_json(),
    )?;
    fs::write(output_dir.join("index.ts"), INDEX_TS)?;
    Ok(())
}

fn push_decl<T: TS>(cfg: &Config, output: &mut String) {
    output.push_str("export ");
    output.push_str(&T::decl(cfg));
    output.push_str("\n\n");
}

#[derive(Debug, Clone, Default, Serialize)]
#[serde(rename_all = "camelCase")]
struct MethodSchemaBinding {
    #[serde(skip_serializing_if = "Option::is_none")]
    outgoing_request: Option<&'static str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    outgoing_notification: Option<&'static str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    incoming_result: Option<&'static str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    incoming_notification: Option<&'static str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    incoming_request: Option<&'static str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    outgoing_response: Option<&'static str>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct ProtocolSchemaBundle {
    schemas: BTreeMap<String, RootSchema>,
    methods: BTreeMap<String, MethodSchemaBinding>,
}

fn protocol_schema_bundle() -> ProtocolSchemaBundle {
    let mut schemas = BTreeMap::new();
    let mut methods = BTreeMap::new();

    register_acp_schemas(&mut schemas, &mut methods);
    register_devo_protocol_schemas(&mut schemas, &mut methods);
    // The Desktop runtime speaks Native exclusively. Register the complete
    // Native method registry last so colliding ACP adapter names (notably
    // session/new, session/list and session/delete) cannot leak ACP wire
    // shapes into the first-party runtime validator.
    register_native_method_registry(&mut schemas, &mut methods);
    register_native_notification_registry(&mut schemas, &mut methods);
    // Replay-carrying result schemas embed the raw schemars ServerNotification
    // definition; align its field names with the wire casing.
    for schema in schemas.values_mut() {
        camel_case_embedded_server_notification(schema);
    }

    ProtocolSchemaBundle { schemas, methods }
}

fn register_native_notification_registry(
    schemas: &mut BTreeMap<String, RootSchema>,
    methods: &mut BTreeMap<String, MethodSchemaBinding>,
) {
    let root = schemars::schema_for!(native::event::ServerNotification);
    let variants = root
        .schema
        .subschemas
        .as_ref()
        .and_then(|subschemas| subschemas.one_of.as_ref())
        .expect("ServerNotification is a tagged union");
    for variant in variants {
        let variant = variant.clone().into_object();
        let Some(object) = variant.object.as_ref() else {
            continue;
        };
        let Some(method_name) = object
            .properties
            .get("method")
            .cloned()
            .and_then(|schema| schema.into_object().enum_values)
            .and_then(|values| values.into_iter().next())
            .and_then(|value| value.as_str().map(str::to_owned))
        else {
            continue;
        };
        let Some(params) = object.properties.get("params") else {
            continue;
        };
        let mut params = params.clone().into_object();
        camel_case_params_fields(&mut params);
        let schema_name = format!(
            "{}NotificationParams",
            method_name
                .split(|character: char| !character.is_ascii_alphanumeric())
                .filter(|segment| !segment.is_empty())
                .map(|segment| {
                    let mut characters = segment.chars();
                    characters
                        .next()
                        .map(|first| first.to_ascii_uppercase().to_string())
                        .unwrap_or_default()
                        + characters.as_str()
                })
                .collect::<String>()
        );
        params.metadata().title = Some(schema_name.clone());
        schemas.insert(
            schema_name.clone(),
            RootSchema {
                meta_schema: root.meta_schema.clone(),
                schema: params,
                definitions: root.definitions.clone(),
            },
        );
        methods
            .entry(method_name)
            .or_default()
            .incoming_notification = Some(Box::leak(schema_name.into_boxed_str()));
    }
}

/// schemars 0.8 does not honor serde's `rename_all_fields`, so generated
/// schema objects keep Rust field names (`restore_plan_id`) while the wire
/// serializes camelCase (`restorePlanId`). Rewrite a notification params
/// schema's field names so validation accepts what the server actually sends.
fn camel_case_params_fields(params: &mut schemars::schema::SchemaObject) {
    if let Some(object) = params.object.as_mut() {
        object.properties = std::mem::take(&mut object.properties)
            .into_iter()
            .map(|(name, schema)| (snake_to_lower_camel(&name), schema))
            .collect();
        object.required = std::mem::take(&mut object.required)
            .into_iter()
            .map(|name| snake_to_lower_camel(&name))
            .collect();
    }
}

/// Apply the same rewrite to the `ServerNotification` definition embedded in
/// replay-carrying result schemas (`SubscriptionCreateResult`). The registry
/// path above already rewrites its standalone copies; without this pass the
/// embedded definition keeps snake_case field names and replay envelope
/// validation rejects every notification whose variant fields are multi-word.
fn camel_case_embedded_server_notification(schema: &mut RootSchema) {
    let Some(definition) = schema.definitions.get_mut("ServerNotification") else {
        return;
    };
    let schemars::schema::Schema::Object(object) = definition else {
        return;
    };
    let Some(subschemas) = object.subschemas.as_mut() else {
        return;
    };
    let Some(branches) = subschemas.one_of.as_mut() else {
        return;
    };
    for branch in branches {
        let schemars::schema::Schema::Object(branch_object) = branch else {
            continue;
        };
        let Some(validation) = branch_object.object.as_mut() else {
            continue;
        };
        let Some(params) = validation.properties.get_mut("params") else {
            continue;
        };
        let schemars::schema::Schema::Object(params_object) = params else {
            continue;
        };
        camel_case_params_fields(params_object);
    }
}

fn snake_to_lower_camel(value: &str) -> String {
    let mut segments = value.split('_');
    let mut result = segments.next().unwrap_or_default().to_string();
    for segment in segments {
        let mut characters = segment.chars();
        if let Some(first) = characters.next() {
            result.push(first.to_ascii_uppercase());
            result.push_str(characters.as_str());
        }
    }
    result
}

/// Write the first-party Native TypeScript wire types to `output_dir`.
pub fn write_native_typescript_dir(output_dir: impl AsRef<Path>) -> io::Result<()> {
    let output_dir = output_dir.as_ref();
    if output_dir.exists() {
        fs::remove_dir_all(output_dir)?;
    }
    fs::create_dir_all(output_dir)?;
    fs::write(output_dir.join("native.ts"), generate_protocol_typescript())?;
    fs::write(
        output_dir.join("schema.json"),
        generate_protocol_schema_json(),
    )?;
    fs::write(output_dir.join("index.ts"), NATIVE_INDEX_TS)?;
    Ok(())
}

fn register_native_method_registry(
    schemas: &mut BTreeMap<String, RootSchema>,
    methods: &mut BTreeMap<String, MethodSchemaBinding>,
) {
    for spec in native::methods::NATIVE_METHODS {
        // Connection negotiation deliberately retains the compatibility
        // initialize envelope; `_meta.devo.protocol = native` selects the
        // Native method surface after negotiation.
        if spec.name == ACP_INITIALIZE_METHOD {
            continue;
        }
        let params = (spec.params_schema)();
        let result = (spec.result_schema)();
        let params_name = root_schema_name(&params);
        let result_name = root_schema_name(&result);
        schemas.insert(params_name.clone(), params);
        schemas.insert(result_name.clone(), result);
        method(
            methods,
            spec.name,
            MethodSchemaBinding {
                outgoing_request: Some(Box::leak(params_name.into_boxed_str())),
                incoming_result: Some(Box::leak(result_name.into_boxed_str())),
                ..MethodSchemaBinding::default()
            },
        );
    }
    for spec in native::methods::REVERSE_METHODS {
        let params = (spec.params_schema)();
        let result = (spec.result_schema)();
        let params_name = root_schema_name(&params);
        let result_name = root_schema_name(&result);
        schemas.insert(params_name.clone(), params);
        schemas.insert(result_name.clone(), result);
        method(
            methods,
            spec.name,
            MethodSchemaBinding {
                incoming_request: Some(Box::leak(params_name.into_boxed_str())),
                outgoing_response: Some(Box::leak(result_name.into_boxed_str())),
                ..MethodSchemaBinding::default()
            },
        );
    }
}

fn root_schema_name(schema: &RootSchema) -> String {
    schema
        .schema
        .metadata
        .as_ref()
        .and_then(|metadata| metadata.title.clone())
        .expect("registered Native schemas have titles")
}

