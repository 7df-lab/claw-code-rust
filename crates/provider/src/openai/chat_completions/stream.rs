/// <https://developers.openai.com/api/reference/resources/chat/subresources/completions/streaming-events>
/// Represents a streamed chunk of a chat completion response returned by the model, based on the provided input.
/// - id: string
///   A unique identifier for the chat completion. Each chunk has the same ID.
/// - choices: array of object
///   A list of chat completion choices. Can contain more than one elements if n is greater than 1. Can also be empty for the last chunk if you set stream_options: {"include_usage": true}.
///   - delta: object
///     A chat completion delta generated by streamed model responses.
///     - content: optional string
///       The contents of the chunk message.
///     - refusal: optional string
///       The refusal message generated by the model.
///     - role: optional "developer" or "system" or "user" or "assistant" or "tool"
///       The role of the author of this message.
///     - tool_calls: optional array of
///       - index: number
///       - id: optional string
///         The ID of the tool call.
///       - function: optional object
///         - arguments: optional string
///           The arguments to call the function with, as generated by the model in JSON format. Note that the model does not always generate valid JSON, and may hallucinate parameters not defined by your function schema. Validate the arguments in your code before calling your function.
///         - name: optional string
///           The name of the function to call.
///       - type: optional "function"
///         The type of the tool. Currently, only function is supported.
///    - finish_reason: "stop" or "length" or "tool_calls" or "content_filter" or "function_call"
///      The reason the model stopped generating tokens. This will be stop if the model hit a natural stop point or a provided stop sequence, length if the maximum number of tokens specified in the request was reached, content_filter if content was omitted due to a flag from our content filters, tool_calls if the model called a tool, or function_call (deprecated) if the model called a function.
///    - index: number
///      The index of the choice in the list of choices.
///    - logprobs: optional object
///      Log probability information for the choice.
/// - created: number
///   The Unix timestamp (in seconds) of when the chat completion was created. Each chunk has the same timestamp.
/// - model: string
///   The model to generate the completion.
/// - object: "chat.completion.chunk"
///   The object type, which is always chat.completion.chunk
/// - service_tier: optional "auto" or "default" or "flex" or "scale" or "priority"
/// - usage: optional CompletionUsage
pub(super) async fn completion_stream(
    provider: &OpenAIProvider,
    request: ModelRequest,
) -> Result<Pin<Box<dyn Stream<Item = Result<StreamEvent>> + Send>>> {
    let body = build_request(&request, true);
    tracing::debug!(
        provider = "openai",
        api_base = %provider.base_url,
        model = %request.model,
        messages = request.messages.len(),
        tools = request.tools.as_ref().map_or(0, Vec::len),
        max_tokens = request.max_tokens,
        http_body = %body,
        "sending openai streaming request"
    );

    let event_source = EventSource::new(provider.streaming_request_builder(&body))
        .context("failed to create openai event source")?;
    let stream = async_stream::try_stream! {
        let mut state = ChatCompletionStreamState::for_request(&request);

        futures::pin_mut!(event_source);
        loop {
            let event = match timeout::next_eventsource_event(&mut event_source).await {
                Ok(Some(event)) => event,
                Ok(None) => break,
                Err(idle) => {
                    Err(timeout::stream_idle_timeout_provider_error(
                        "openai",
                        &request.model,
                        idle,
                    ))?
                }
            };
            let event = match event {
                Ok(event) => event,
                Err(reqwest_eventsource::Error::InvalidStatusCode(status, response)) => {
                    Err(invalid_status_error(
                        "openai",
                        &request.model,
                        "stream",
                        status,
                        response,
                        &body,
                    )
                    .await)?
                }
                Err(error) => Err(stream_error(format!(
                    "openai stream error for model {}: {error}",
                    request.model
                )))?,
            };

            match event {
                Event::Open => {}
                Event::Message(message) => {
                    tracing::debug!(
                        stream_elapsed_ms = stream_trace_elapsed_ms(),
                        event = %message.event,
                        data_len = message.data.len(),
                        "openai chat completions stream chunk received"
                    );
                    tracing::trace!(
                        event = %message.event,
                        data_len = message.data.len(),
                        data = %message.data,
                        "openai chat completions raw stream event"
                    );
                    if message.data == "[DONE]" {
                        break;
                    }

                    let value: Value = serde_json::from_str(&message.data)
                        .map_err(|error| {
                            anyhow::anyhow!("failed to parse openai stream chunk: {error}")
                        })?;
                    if let Some(error) = provider_error_from_payload(&value, &request) {
                        Err(error)?;
                    }
                    let chunk: ChatCompletionStreamChunk = serde_json::from_value(value)
                        .map_err(|error| {
                            anyhow::anyhow!("failed to deserialize openai stream chunk: {error}")
                        })?;

                    for stream_event in state.apply_chunk(chunk) {
                        if let StreamEvent::TextDelta { index, text } = &stream_event {
                            if let Some(assistant_token_text) = assistant_token_log_preview(text) {
                                tracing::debug!(
                                    stream_elapsed_ms = stream_trace_elapsed_ms(),
                                    index,
                                    delta_len = text.len(),
                                    assistant_token_text = %assistant_token_text,
                                    "openai chat completions text delta emitted"
                                );
                            } else {
                                tracing::debug!(
                                    stream_elapsed_ms = stream_trace_elapsed_ms(),
                                    index,
                                    delta_len = text.len(),
                                    "openai chat completions text delta emitted"
                                );
                            }
                        }
                        yield stream_event;
                    }
                }
            }
        }

        for stream_event in state.finish_pending_content() {
            yield stream_event;
        }
        yield StreamEvent::MessageDone {
            response: state.into_response(),
        };
    };

    Ok(Box::pin(stream))
}

fn stream_error(message: String) -> ProviderError {
    ProviderError::StreamError {
        message,
        bytes_received: None,
    }
}

fn stream_trace_elapsed_ms() -> u128 {
    static STREAM_TRACE_START: OnceLock<Instant> = OnceLock::new();
    STREAM_TRACE_START
        .get_or_init(Instant::now)
        .elapsed()
        .as_millis()
}

fn assistant_token_log_preview(text: &str) -> Option<String> {
    assistant_token_logging_enabled()
        .then(|| format_assistant_token_log_preview(text, assistant_token_log_max_chars()))
}

fn assistant_token_logging_enabled() -> bool {
    static ASSISTANT_TOKEN_LOGGING_ENABLED: OnceLock<bool> = OnceLock::new();
    *ASSISTANT_TOKEN_LOGGING_ENABLED.get_or_init(|| {
        std::env::var("DEVO_LOG_ASSISTANT_TOKEN_TEXT")
            .ok()
            .is_some_and(|value| {
                matches!(
                    value.as_str(),
                    "1" | "true" | "TRUE" | "yes" | "YES" | "on" | "ON"
                )
            })
    })
}

fn assistant_token_log_max_chars() -> usize {
    static ASSISTANT_TOKEN_LOG_MAX_CHARS: OnceLock<usize> = OnceLock::new();
    *ASSISTANT_TOKEN_LOG_MAX_CHARS.get_or_init(|| {
        std::env::var("DEVO_ASSISTANT_TOKEN_LOG_MAX_CHARS")
            .ok()
            .and_then(|value| value.parse::<usize>().ok())
            .filter(|value| *value > 0)
            .unwrap_or(512)
    })
}

fn format_assistant_token_log_preview(text: &str, max_chars: usize) -> String {
    let max_chars = max_chars.max(1);
    let mut preview = String::new();
    let mut chars = text.chars();
    for ch in chars.by_ref().take(max_chars) {
        preview.extend(ch.escape_default());
    }
    if chars.next().is_some() {
        preview.push_str("...");
    }
    preview
}

#[derive(Debug, Default)]
struct ChatCompletionStreamState {
    response_id: String,
    created: Option<u64>,
    model: Option<String>,
    object: Option<String>,
    service_tier: Option<String>,
    system_fingerprint: Option<String>,
    text: StreamTextBlock,
    text_parser: TaggedTextParser,
    reasoning: StreamTextBlock,
    reasoning_content_active: bool,
    refusal: String,
    role: Option<String>,
    tool_calls: BTreeMap<u32, PartialToolCall>,
    choice_metadata: BTreeMap<u32, StreamChoiceMetadata>,
    finish_reason: Option<StopReason>,
    usage: Option<Usage>,
    dsml_healer: DsmlToolCallHealer,
    dsml_text_filter: Option<DsmlTextStreamFilter>,
}

impl ChatCompletionStreamState {
    fn for_request(request: &ModelRequest) -> Self {
        Self::with_healer(DsmlToolCallHealer::for_request(request))
    }

    #[cfg(test)]
    fn for_model(model: &str) -> Self {
        Self::with_healer(DsmlToolCallHealer::for_model(model))
    }

    fn with_healer(dsml_healer: DsmlToolCallHealer) -> Self {
        Self {
            dsml_text_filter: dsml_healer.text_stream_filter(),
            dsml_healer,
            ..Self::default()
        }
    }

    fn apply_chunk(&mut self, chunk: ChatCompletionStreamChunk) -> Vec<StreamEvent> {
        let mut events = Vec::new();

        if self.response_id.is_empty()
            && let Some(id) = chunk.id
        {
            self.response_id = id;
        }
        if self.created.is_none() {
            self.created = chunk.created;
        }
        if self.model.is_none() {
            self.model = chunk.model;
        }
        if self.object.is_none() {
            self.object = chunk.object;
        }
        if self.service_tier.is_none() {
            self.service_tier = chunk.service_tier;
        }
        if self.system_fingerprint.is_none() {
            self.system_fingerprint = chunk.system_fingerprint;
        }

        if let Some(usage) = chunk.usage.map(usage_from_completion_usage) {
            self.usage = Some(usage.clone());
            events.push(StreamEvent::UsageDelta(usage));
        }

        for choice in chunk.choices {
            self.apply_choice(choice, &mut events);
        }

        events
    }

    fn apply_choice(&mut self, choice: ChatCompletionStreamChoice, events: &mut Vec<StreamEvent>) {
        let choice_index = choice.index.unwrap_or(0);
        self.choice_metadata.entry(choice_index).or_default().index = Some(choice_index);
        self.choice_metadata
            .entry(choice_index)
            .or_default()
            .logprobs = choice.logprobs.clone();

        if let Some(role) = choice.delta.role.as_deref() {
            self.role = Some(role.to_string());
        }
        if let Some(refusal) = choice.delta.refusal.filter(|refusal| !refusal.is_empty()) {
            self.refusal.push_str(&refusal);
        }

        match choice.delta.reasoning_content {
            Some(reasoning_content) => {
                self.reasoning_content_active = true;
                if !reasoning_content.is_empty() {
                    self.push_reasoning_delta(reasoning_content, events);
                }
            }
            None if self.reasoning_content_active => {
                self.reasoning_content_active = false;
                self.push_reasoning_done(events);
            }
            None => {}
        }

        if let Some(content) = choice.delta.content.filter(|content| !content.is_empty()) {
            for fragment in self.text_parser.consume(&content) {
                match fragment {
                    TaggedTextFragment::Text(text) => self.push_text_delta(text, events),
                    TaggedTextFragment::Reasoning(text) => self.push_reasoning_delta(text, events),
                }
            }
        }

        for (fallback_index, tool_call_delta) in choice.delta.tool_calls.into_iter().enumerate() {
            let fallback_index = u32::try_from(fallback_index).unwrap_or(u32::MAX);
            self.apply_tool_call_delta(tool_call_delta, fallback_index, events);
        }

        if let Some(reason) = choice.finish_reason {
            self.finish_pending_content_into(events);
            self.finish_reason = Some(parse_finish_reason(&reason));
            self.choice_metadata
                .entry(choice_index)
                .or_default()
                .finish_reason = Some(reason);
        }
    }

    fn push_text_delta(&mut self, text: String, events: &mut Vec<StreamEvent>) {
        if text.is_empty() {
            return;
        }
        self.text.value.push_str(&text);
        let text_chunks = if let Some(filter) = &mut self.dsml_text_filter {
            filter.consume(&text)
        } else {
            vec![text]
        };
        self.push_visible_text_delta(text_chunks, events);
    }

    fn push_visible_text_delta(&mut self, text_chunks: Vec<String>, events: &mut Vec<StreamEvent>) {
        for text in text_chunks {
            if text.is_empty() {
                continue;
            }
            if !self.text.started {
                self.text.started = true;
                events.push(StreamEvent::TextStart { index: 0 });
            }
            events.push(StreamEvent::TextDelta { index: 0, text });
        }
    }

    fn finish_pending_content(&mut self) -> Vec<StreamEvent> {
        let mut events = Vec::new();
        self.finish_pending_content_into(&mut events);
        events
    }

    fn finish_pending_content_into(&mut self, events: &mut Vec<StreamEvent>) {
        self.finish_tagged_text_into(events);
        self.finish_pending_text_into(events);
        self.finish_reasoning_into(events);
    }

    fn finish_tagged_text_into(&mut self, events: &mut Vec<StreamEvent>) {
        for fragment in self.text_parser.finish() {
            match fragment {
                TaggedTextFragment::Text(text) => self.push_text_delta(text, events),
                TaggedTextFragment::Reasoning(text) => self.push_reasoning_delta(text, events),
            }
        }
    }

    fn finish_pending_text_into(&mut self, events: &mut Vec<StreamEvent>) {
        let Some(filter) = &mut self.dsml_text_filter else {
            return;
        };
        let text_chunks = filter.finish();
        self.push_visible_text_delta(text_chunks, events);
    }

    fn push_reasoning_delta(&mut self, text: String, events: &mut Vec<StreamEvent>) {
        if text.is_empty() {
            return;
        }
        if !self.reasoning.started || self.reasoning.finished {
            self.reasoning.started = true;
            self.reasoning.finished = false;
            events.push(StreamEvent::ReasoningStart { index: 1 });
        }
        self.reasoning.value.push_str(&text);
        events.push(StreamEvent::ReasoningDelta { index: 1, text });
    }

    fn finish_reasoning_into(&mut self, events: &mut Vec<StreamEvent>) {
        self.reasoning_content_active = false;
        self.push_reasoning_done(events);
    }

    fn push_reasoning_done(&mut self, events: &mut Vec<StreamEvent>) {
        if self.reasoning.started && !self.reasoning.finished {
            self.reasoning.finished = true;
            events.push(StreamEvent::ReasoningDone { index: 1 });
        }
    }

    fn apply_tool_call_delta(
        &mut self,
        tool_call_delta: ChatCompletionStreamToolCallDelta,
        fallback_index: u32,
        events: &mut Vec<StreamEvent>,
    ) {
        let ChatCompletionStreamToolCallDelta {
            index,
            id,
            kind,
            function,
            custom,
        } = tool_call_delta;
        let index = index.unwrap_or(fallback_index);
        let content_index =
            usize::try_from(index).map_or(usize::MAX, |index| index.saturating_add(1));
        let entry = self.tool_calls.entry(index).or_default();

        if let Some(id) = id {
            entry.id = id;
        }
        if let Some(kind) = kind.as_deref().and_then(ToolCallKind::from_wire) {
            entry.kind = kind;
        }

        let mut function_arguments_delta = None;
        if let Some(function) = function {
            if let Some(name) = function.name {
                entry.name = name;
            }

            if let Some(arguments) = function.arguments.filter(|arguments| !arguments.is_empty()) {
                function_arguments_delta = Some(arguments.clone());
                entry.arguments_json.push_str(&arguments);
            }
        }

        let mut custom_input_delta = None;
        if let Some(custom) = custom {
            if let Some(name) = custom.name {
                entry.name = name;
            }
            if let Some(input) = custom.input.filter(|input| !input.is_empty()) {
                custom_input_delta = Some(input.clone());
                entry.arguments_json.push_str(&input);
            }
        }

        let newly_started = if !entry.started && tool_call_delta_starts_block(entry) {
            entry.started = true;
            events.push(StreamEvent::ToolCallStart {
                index: content_index,
                id: entry.id.clone(),
                name: entry.name.clone(),
                input: entry.kind.empty_input(),
            });
            true
        } else {
            false
        };

        if newly_started {
            if !entry.arguments_json.is_empty() {
                events.push(StreamEvent::ToolCallInputDelta {
                    index: content_index,
                    partial_json: entry.arguments_json.clone(),
                });
            }
            return;
        }

        if entry.started
            && let Some(arguments) = function_arguments_delta
        {
            events.push(StreamEvent::ToolCallInputDelta {
                index: content_index,
                partial_json: arguments,
            });
        }
        if entry.started
            && let Some(input) = custom_input_delta
        {
            events.push(StreamEvent::ToolCallInputDelta {
                index: content_index,
                partial_json: input,
            });
        }
    }

    fn metadata(&self) -> ResponseMetadata {
        let mut metadata = ResponseMetadata::default();

        if !self.reasoning.value.is_empty() {
            metadata.extras.push(ResponseExtra::ReasoningText {
                text: self.reasoning.value.clone(),
            });
        }

        if let Some(payload) = self.provider_specific_payload() {
            metadata.extras.push(ResponseExtra::ProviderSpecific {
                provider: "openai".to_string(),
                payload,
            });
        }

        metadata
    }

    fn provider_specific_payload(&self) -> Option<Value> {
        let response = self.as_provider_response();
        build_provider_specific_response_payload(&response)
    }

    fn as_provider_response(&self) -> super::OpenAIChatCompletionResponse {
        super::OpenAIChatCompletionResponse {
            id: self.response_id.clone(),
            choices: self.provider_choices(),
            created: self.created,
            model: self.model.clone(),
            object: self.object.clone(),
            service_tier: self.service_tier.clone(),
            system_fingerprint: self.system_fingerprint.clone(),
            usage: self.usage.as_ref().map(|usage| OpenAICompletionUsage {
                prompt_tokens: usage.input_tokens,
                completion_tokens: usage.output_tokens,
                total_tokens: usage.total_tokens,
                prompt_tokens_details: Some(super::OpenAIPromptTokenDetails {
                    audio_tokens: None,
                    cached_tokens: usage.cache_read_input_tokens,
                }),
                completion_tokens_details: usage.reasoning_output_tokens.map(|reasoning_tokens| {
                    super::OpenAICompletionTokenDetails {
                        accepted_prediction_tokens: None,
                        audio_tokens: None,
                        reasoning_tokens: Some(reasoning_tokens),
                        rejected_prediction_tokens: None,
                    }
                }),
            }),
        }
    }

    fn provider_choices(&self) -> Vec<OpenAIChatCompletionChoice> {
        let message = OpenAIChatCompletionMessage {
            content: if self.text.value.is_empty() {
                None
            } else {
                Some(self.text.value.clone())
            },
            refusal: if self.refusal.is_empty() {
                None
            } else {
                Some(self.refusal.clone())
            },
            role: self.role.clone(),
            annotations: Vec::new(),
            audio: None,
            function_call: None,
            tool_calls: self.provider_tool_calls(),
            reasoning_content: if self.reasoning.value.is_empty() {
                None
            } else {
                Some(self.reasoning.value.clone())
            },
        };

        if self.choice_metadata.is_empty()
            && message.content.is_none()
            && message.refusal.is_none()
            && message.tool_calls.is_empty()
            && self.finish_reason.is_none()
        {
            return Vec::new();
        }

        if self.choice_metadata.is_empty() {
            return vec![OpenAIChatCompletionChoice {
                finish_reason: self
                    .finish_reason
                    .as_ref()
                    .map(stop_reason_to_finish_reason),
                index: Some(0),
                logprobs: None,
                message: Some(message),
            }];
        }

        self.choice_metadata
            .iter()
            .map(|(index, metadata)| OpenAIChatCompletionChoice {
                finish_reason: metadata.finish_reason.clone().or_else(|| {
                    self.finish_reason
                        .as_ref()
                        .map(stop_reason_to_finish_reason)
                }),
                index: Some(*index),
                logprobs: metadata.logprobs.clone(),
                message: Some(message.clone()),
            })
            .collect()
    }

    fn provider_tool_calls(&self) -> Vec<OpenAIChatCompletionMessageToolCall> {
        self.tool_calls
            .values()
            .cloned()
            .map(PartialToolCall::into_provider_tool_call)
            .collect()
    }

    fn ordered_content(
        text: StreamTextBlock,
        tool_calls: BTreeMap<u32, PartialToolCall>,
    ) -> Vec<ResponseContent> {
        let mut content = Vec::new();

        if !text.value.is_empty() {
            content.push(ResponseContent::Text(text.value));
        }

        for tool_call in tool_calls.into_values() {
            let provider_tool_call = tool_call.into_provider_tool_call();
            if let Some(content_block) = parse_tool_use(&provider_tool_call) {
                content.push(content_block);
            }
        }

        content
    }

    fn into_response(self) -> ModelResponse {
        let usage = self.usage.clone().unwrap_or_default();
        let metadata = self.metadata();
        let ChatCompletionStreamState {
            response_id,
            finish_reason,
            text,
            tool_calls,
            dsml_healer,
            ..
        } = self;
        let content = dsml_healer.heal_response_content(Self::ordered_content(text, tool_calls));

        ModelResponse {
            id: response_id,
            content,
            stop_reason: finish_reason,
            usage,
            metadata,
        }
    }
}

fn tool_call_delta_starts_block(entry: &PartialToolCall) -> bool {
    !entry.id.is_empty() && !entry.name.is_empty()
}

fn usage_from_completion_usage(usage: OpenAICompletionUsage) -> Usage {
    Usage {
        input_tokens: usage.prompt_tokens,
        output_tokens: usage.completion_tokens,
        cache_creation_input_tokens: None,
        cache_read_input_tokens: usage
            .prompt_tokens_details
            .as_ref()
            .and_then(|details| details.cached_tokens),
        reasoning_output_tokens: usage
            .completion_tokens_details
            .as_ref()
            .and_then(|details| details.reasoning_tokens),
        total_tokens: usage.total_tokens,
    }
}

#[derive(Debug, Default)]
struct StreamTextBlock {
    value: String,
    started: bool,
    finished: bool,
}

#[derive(Debug, Clone, Default)]
struct PartialToolCall {
    id: String,
    name: String,
    arguments_json: String,
    started: bool,
    kind: ToolCallKind,
}

impl PartialToolCall {
    fn into_provider_tool_call(self) -> OpenAIChatCompletionMessageToolCall {
        match self.kind {
            ToolCallKind::Function => OpenAIChatCompletionMessageToolCall {
                id: self.id,
                kind: "function".to_string(),
                function: Some(OpenAIChatCompletionFunctionCall {
                    arguments: self.arguments_json,
                    name: self.name,
                }),
                custom: None,
            },
            ToolCallKind::Custom => OpenAIChatCompletionMessageToolCall {
                id: self.id,
                kind: "custom".to_string(),
                function: None,
                custom: Some(OpenAIChatCompletionCustomToolCall {
                    input: self.arguments_json,
                    name: self.name,
                }),
            },
        }
    }
}

#[derive(Debug, Default)]
struct StreamChoiceMetadata {
    index: Option<u32>,
    finish_reason: Option<String>,
    logprobs: Option<OpenAIChoiceLogprobs>,
}

#[derive(Debug, Clone, Copy, Default)]
enum ToolCallKind {
    #[default]
    Function,
    Custom,
}

impl ToolCallKind {
    fn from_wire(value: &str) -> Option<Self> {
        match value {
            "function" => Some(Self::Function),
            "custom" => Some(Self::Custom),
            _ => None,
        }
    }

    fn empty_input(self) -> Value {
        match self {
            Self::Function => Value::Object(serde_json::Map::new()),
            Self::Custom => Value::String(String::new()),
        }
    }
}

#[derive(Debug, Deserialize)]
struct ChatCompletionStreamChunk {
    #[serde(default)]
    id: Option<String>,
    #[serde(default)]
    created: Option<u64>,
    #[serde(default)]
    model: Option<String>,
    #[serde(default)]
    object: Option<String>,
    #[serde(default)]
    service_tier: Option<String>,
    #[serde(default)]
    system_fingerprint: Option<String>,
    #[serde(default, deserialize_with = "deserialize_null_vec")]
    choices: Vec<ChatCompletionStreamChoice>,
    #[serde(default)]
    usage: Option<OpenAICompletionUsage>,
}

#[derive(Debug, Default, Deserialize)]
struct ChatCompletionStreamChoice {
    #[serde(default)]
    delta: ChatCompletionStreamDelta,
    #[serde(default)]
    index: Option<u32>,
    #[serde(default)]
    finish_reason: Option<String>,
    #[serde(default)]
    logprobs: Option<OpenAIChoiceLogprobs>,
}

#[derive(Debug, Default, Deserialize)]
struct ChatCompletionStreamDelta {
    #[serde(default)]
    role: Option<String>,
    #[serde(default)]
    content: Option<String>,
    #[serde(default)]
    reasoning_content: Option<String>,
    #[serde(default)]
    refusal: Option<String>,
    #[serde(default, deserialize_with = "deserialize_null_vec")]
    tool_calls: Vec<ChatCompletionStreamToolCallDelta>,
}

fn deserialize_null_vec<'de, D, T>(deserializer: D) -> std::result::Result<Vec<T>, D::Error>
where
    D: serde::Deserializer<'de>,
    T: serde::Deserialize<'de>,
{
    Option::<Vec<T>>::deserialize(deserializer).map(|v| v.unwrap_or_default())
}

#[derive(Debug, Default, Deserialize)]
struct ChatCompletionStreamToolCallDelta {
    #[serde(default)]
    index: Option<u32>,
    #[serde(default)]
    id: Option<String>,
    #[serde(rename = "type", default)]
    kind: Option<String>,
    #[serde(default)]
    function: Option<ChatCompletionStreamFunctionDelta>,
    #[serde(default)]
    custom: Option<ChatCompletionStreamCustomDelta>,
}

#[derive(Debug, Default, Deserialize)]
struct ChatCompletionStreamFunctionDelta {
    #[serde(default)]
    name: Option<String>,
    #[serde(default)]
    arguments: Option<String>,
}

#[derive(Debug, Default, Deserialize)]
struct ChatCompletionStreamCustomDelta {
    #[serde(default)]
    name: Option<String>,
    #[serde(default)]
    input: Option<String>,
}

fn stop_reason_to_finish_reason(reason: &StopReason) -> String {
    match reason {
        StopReason::ToolUse => "tool_calls".to_string(),
        StopReason::MaxTokens => "length".to_string(),
        StopReason::EndTurn => "stop".to_string(),
        StopReason::StopSequence => "content_filter".to_string(),
    }
}

